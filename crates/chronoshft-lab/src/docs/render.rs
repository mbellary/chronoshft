fn test_details(p: &mut Page, t: &Value) {
    p.para(format!(
        "### {} — {} {{ #{} }}",
        id(t),
        s(&t["title"]),
        low(t)
    ));
    p.para(format!(
        "Revision {} · {} · {} · {} · binding {}",
        s(&t["revision"]),
        obligation(t),
        s(&t["classification"]),
        s(&t["execution_type"]),
        s(&t["execution_binding"]["state"])
    ));
    p.para(format!(
        "**Applicable validations:** {}.",
        a(&t["validations"])
            .iter()
            .map(|v| val_ref(v, "../"))
            .collect::<Vec<_>>()
            .join(", ")
    ));
    p.para(format!(
        "**Hypotheses:** {}.",
        join(&t["hypothesis_ids"], ", ")
    ));
    p.list(
        "**Setup and prerequisites**",
        a(&t["preconditions"]).iter().map(s),
    );
    p.para("**Procedure**");
    p.0.extend(
        a(&t["procedure"])
            .iter()
            .enumerate()
            .map(|(i, v)| format!("{}. {}", i + 1, s(v))),
    );
    p.0.push(String::new());
    p.list("**Expected outcome**", a(&t["expected"]).iter().map(s));
    p.para(format!(
        "**Independent oracle:** {}",
        s(&t["oracle"]["description"])
    ));
    p.para(format!(
        "**Execution method:** {}",
        s(&t["execution_method"])
    ));
    p.list(
        "**Required evidence**",
        a(&t["required_evidence"]).iter().map(s),
    );
}
fn experiment(e: &Value, r: &Records) -> String {
    let tests: Vec<_> = a(&e["tests"]).iter().map(|t| &r[&id(t)]).collect();
    let runs: Vec<_> = rows(r, "RUN-")
        .into_iter()
        .filter(|v| v["experiment"]["id"] == e["id"])
        .collect();
    let run_ids: BTreeSet<_> = runs.iter().map(|v| id(v)).collect();
    let val_ids: BTreeSet<_> = a(&e["validates"]).iter().map(id).collect();
    let evidence: Vec<_> = rows(r, "EVD-")
        .into_iter()
        .filter(|v| {
            run_ids.contains(&s(&v["provenance"]["execution_id"]))
                || a(&v["supports"])
                    .iter()
                    .any(|v| val_ids.contains(&id(&v["validation"])))
        })
        .collect();
    let mut p = Page::default();
    p.para(format!(
        "Revision {} · {} · lifecycle {}",
        s(&e["revision"]),
        s(&e["method"]["kind"]),
        s(&e["lifecycle"]["state"])
    ));
    p.para(format!(
        "**Validations:** {}.",
        a(&e["validates"])
            .iter()
            .map(|v| val_ref(v, "../"))
            .collect::<Vec<_>>()
            .join(", ")
    ));
    p.lines(&[EXPERIMENT_3, "", "## Purpose and technical background", ""]);
    p.para(s(&e["objective"]));
    for v in a(&e["validates"]) {
        let v = &r[&id(v)];
        p.para(format!(
            "**{} historical finding:** {}",
            id(v),
            s(&v["origin"]["finding"])
        ));
    }
    p.lines(&[
        "These are preserved research findings, not new source audits or experiment outcomes.",
        "",
        "## Hypotheses",
        "",
    ]);
    p.bullets(
        a(&e["hypotheses"])
            .iter()
            .map(|h| format!("**{}:** {}", id(h), s(&h["statement"]))),
    );
    p.lines(&["", "## Design and reference material", "", EXPERIMENT_4, ""]);
    let classes: BTreeSet<_> = tests.iter().map(|t| s(&t["classification"])).collect();
    let mut related = Vec::new();
    for cl in classes {
        for entry in references(&cl) {
            if !related.contains(entry) {
                related.push(*entry);
            }
        }
    }
    p.bullets(
        related
            .iter()
            .map(|(title, path)| format!("[{title}](../../{path})")),
    );
    p.lines(&["", "## Implementation boundary, inputs and outputs", ""]);
    p.para(s(&e["scope"]));
    p.para(format!(
        "**Investigation method:** {}",
        s(&e["method"]["procedure"])
    ));
    p.para(format!(
        "**Implementation path:** {}",
        e["method"]["implementation_path"]
            .as_str()
            .filter(|s| !s.is_empty())
            .map(|s| format!("`{s}`"))
            .unwrap_or_else(|| "Unassigned; no implementation is asserted.".into())
    ));
    p.list(
        "**Prerequisites and dependencies**",
        a(&e["dependencies"]).iter().map(s),
    );
    p.para(EXPERIMENT_5);
    p.list("**Exclusions**", a(&e["exclusions"]).iter().map(s));
    p.para("## Tests and acceptance criteria { #tests }");
    p.table(
        &["Test", "Hypotheses", "Mode", "Obligation", "Binding"],
        tests
            .iter()
            .map(|t| {
                vec![
                    format!("[{} — {}](#{})", id(t), c(&t["title"]), low(t)),
                    join(&t["hypothesis_ids"], ", "),
                    c(&t["execution_type"]),
                    obligation(t).into(),
                    c(&t["execution_binding"]["state"]),
                ]
            })
            .collect(),
        "No test specifications registered.",
    );
    for t in &tests {
        test_details(&mut p, t);
    }
    p.lines(&["## Build, test and benchmark methods", "", EXPERIMENT_6, ""]);
    let bound: Vec<_> = tests
        .iter()
        .filter(|t| t["execution_binding"]["state"] == "bound")
        .collect();
    if bound.is_empty() {
        p.para("No build, test or benchmark commands are bound. All specified procedures remain preparation work.");
    } else {
        p.table(
            &[
                "Test",
                "Implementation path",
                "Bound command / review entrypoint",
            ],
            bound
                .iter()
                .map(|t| {
                    vec![
                        test(t, "../"),
                        cell(
                            t["execution_binding"]["implementation_path"]
                                .as_str()
                                .filter(|s| !s.is_empty())
                                .unwrap_or("Manual procedure"),
                        ),
                        c(&t["execution_binding"]["entrypoint"]),
                    ]
                })
                .collect(),
            "",
        );
    }
    p.para("## Recorded runs and evidence");
    p.table(
        &["Run", "Experiment revision tested", "Recorded outcome"],
        runs.iter()
            .map(|v| {
                vec![
                    run(id(v), "../"),
                    s(&v["experiment"]["revision"]),
                    c(&v["outcome"]),
                ]
            })
            .collect(),
        EXPERIMENT_10,
    );
    p.table(
        &["Evidence", "Relationship"],
        evidence
            .iter()
            .map(|v| {
                vec![
                    ev(id(v), "../"),
                    if run_ids.contains(&s(&v["provenance"]["execution_id"])) {
                        "Produced by an experiment run"
                    } else {
                        "Supports a linked validation; relevance remains subject to review"
                    }
                    .into(),
                ]
            })
            .collect(),
        "No evidence manifests support this experiment or its linked validations.",
    );
    p.para("## Findings, limitations and conclusion");
    p.para(if runs.is_empty() {
        EXPERIMENT_8
    } else {
        EXPERIMENT_9
    });
    p.para("## Architecture implications and next actions");
    p.table(
        &["Validation", "Current disposition", "Decision"],
        a(&e["validates"])
            .iter()
            .map(|v| {
                let val = &r[&id(v)];
                vec![
                    format!("[{}](../validation-coverage.md#{})", id(v), low(v)),
                    cell(disposition(val, r)),
                    val["current_decision_id"]
                        .as_str()
                        .map(|i| dec(i, "../"))
                        .unwrap_or_else(|| "No decision".into()),
                ]
            })
            .collect(),
        "",
    );
    p.para(EXPERIMENT_7);
    p.list(
        "**Completion requirements**",
        a(&e["completion_criteria"]).iter().map(s),
    );
    p.finish(&format!("{} — {}", id(e), s(&e["title"])))
}
