// Python's default JSON presentation is part of the command-table byte contract.
fn command_json(v: &Value) -> String {
    fn ascii(s: &str) -> String {
        let mut result = String::new();
        for ch in s.chars() {
            if ch.is_ascii() && ch != '\u{7f}' {
                result.push(ch);
            } else {
                let mut units = [0; 2];
                for unit in ch.encode_utf16(&mut units) {
                    result.push_str(&format!("\\u{unit:04x}"));
                }
            }
        }
        result
    }
    format!(
        "[{}]",
        a(v).iter()
            .map(|v| ascii(&serde_json::to_string(v).unwrap()))
            .collect::<Vec<_>>()
            .join(", ")
    )
}
fn executions(r: &Records) -> String {
    let mut p = Page::default();
    let runs = rows(r, "RUN-");
    p.lines(&[EXECUTIONS_1, "", "## Execution register", ""]);
    p.table(
        &[
            "Run",
            "Experiment revision",
            "Started (UTC)",
            "Recorded outcome",
            "Test outcomes",
            "Evidence",
        ],
        runs.iter()
            .map(|v| {
                vec![
                    run(id(v), ""),
                    format!(
                        "{} r{}",
                        exp(s(&v["experiment"]["id"]), ""),
                        s(&v["experiment"]["revision"])
                    ),
                    c(&v["started_at"]),
                    c(&v["outcome"]),
                    a(&v["tests"]).len().to_string(),
                    otherwise(
                        a(&v["evidence_ids"])
                            .iter()
                            .map(|i| ev(s(i), ""))
                            .collect::<Vec<_>>()
                            .join(", "),
                        "None",
                    ),
                ]
            })
            .collect(),
        EXECUTIONS_2,
    );
    for v in runs {
        p.para(format!("## {} {{ #{} }}", id(v), low(v)));
        p.para(format!(
            "**Recorded outcome:** {}. **Time:** {} to {}.",
            c(&v["outcome"]),
            c(&v["started_at"]),
            c(&v["ended_at"])
        ));
        p.para(format!(
            "**Registry commit:** `{}`. **Implementation commit:** `{}`. **Dirty:** {}.",
            s(&v["source"]["registry_commit"]),
            s(&v["source"]["implementation_commit"]),
            v["source"]["dirty"]
        ));
        p.para(format!(
            "**Working directory:** {}. **Source/input changed during run:** {}.",
            c(&v["working_directory"]),
            v["source"]["changed_during_run"]
        ));
        p.list(
            "**Exact recorded procedure**",
            a(&v["procedure"]).iter().map(s),
        );
        p.table(
            &[
                "Test revision",
                "Recorded outcome",
                "Exit",
                "Duration (s)",
                "Details",
                "Evidence",
            ],
            a(&v["tests"])
                .iter()
                .map(|t| {
                    vec![
                        format!(
                            "{} r{}",
                            test(&r[&id(&t["test"])], ""),
                            s(&t["test"]["revision"])
                        ),
                        c(&t["outcome"]),
                        if t["exit_code"].is_null() {
                            "Not observed".into()
                        } else {
                            s(&t["exit_code"])
                        },
                        format!("{:.6}", t["duration_seconds"].as_f64().unwrap()),
                        c(&t["details"]),
                        otherwise(
                            a(&t["evidence_ids"])
                                .iter()
                                .map(|i| ev(s(i), ""))
                                .collect::<Vec<_>>()
                                .join(", "),
                            "None",
                        ),
                    ]
                })
                .collect(),
            "No individual test outcomes recorded.",
        );
        p.list(
            "**Case commands**",
            a(&v["tests"])
                .iter()
                .map(|t| format!("{}: {}", id(&t["test"]), cell(command_json(&t["command"])))),
        );
        p.list(
            "**Inputs**",
            a(&v["inputs"]).iter().map(|i| {
                format!(
                    "{}: {} · SHA-256 `{}`",
                    c(&i["name"]),
                    c(&i["reference"]),
                    s(&i["sha256"])
                )
            }),
        );
        p.list(
            "**Dependency lockfiles**",
            a(&v["source"]["dependency_lockfiles"])
                .iter()
                .map(|i| format!("{} · SHA-256 `{}`", c(&i["path"]), s(&i["sha256"]))),
        );
        p.para(format!(
            "**Seeds:** {}.",
            cell(otherwise(join(&v["random_seeds"], ", "), "None recorded"))
        ));
        p.para(format!("**Instrumentation:** {}", c(&v["instrumentation"])));
        for (key, title) in [
            ("failures", "**Failures**"),
            ("skips", "**Skips**"),
            ("tool_errors", "**Tool errors**"),
        ] {
            p.list(title, a(&v[key]).iter().map(s));
        }
        p.para(format!(
            "**Supersedes:** {}. Originals remain retained.",
            v["supersedes"]
                .as_str()
                .map(|i| run(i, ""))
                .unwrap_or_else(|| "None".into())
        ));
    }
    p.finish("Execution register")
}
