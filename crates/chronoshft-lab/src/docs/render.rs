/// Render already-validated registry records without filesystem writes.
pub fn documents(records: &Records) -> BTreeMap<PathBuf, String> {
    let mut result = BTreeMap::new();
    for (filename, content) in [
        ("index", overview(records)),
        ("validation-coverage", coverage(records)),
        ("experiment-register", experiment_register(records)),
        ("test-register", test_register(records)),
        ("execution-register", executions(records)),
        ("evidence-register", evidence(records)),
        ("validation-results", results(records)),
        ("environment-profiles", environments(records)),
    ] {
        result.insert(PathBuf::from(format!("{LAB}/{filename}.md")), content);
    }
    result.insert(
        "docs/00-governance/validation-coverage.md".into(),
        legacy_coverage(records),
    );
    result.insert(
        "docs/00-governance/validation-tests.md".into(),
        legacy_tests(records),
    );
    for e in rows(records, "EXP-") {
        result.insert(
            PathBuf::from(format!("{LAB}/experiments/{}.md", id(e))),
            experiment(e, records),
        );
    }
    result
}
pub fn navigation(records: &Records) -> String {
    let mut lines = vec![NAV_START.into(), "  - Technical Validation Lab:".into()];
    for (label, file) in [
        ("Overview", "index"),
        ("Methodology", "methodology"),
        ("Validation coverage", "validation-coverage"),
        ("Experiment register", "experiment-register"),
        ("Test register", "test-register"),
        ("Execution register", "execution-register"),
        ("Evidence register", "evidence-register"),
        ("Validation results", "validation-results"),
        ("Environment profiles", "environment-profiles"),
        ("Automation and CI", "automation-and-ci"),
        ("Execution and evidence", "execution-and-evidence"),
    ] {
        lines.push(format!("      - {label}: 10-validation-lab/{file}.md"));
    }
    lines.push("      - Experiments:".into());
    for e in rows(records, "EXP-") {
        let title = serde_json::to_string(&format!("{} — {}", id(e), s(&e["title"]))).unwrap();
        lines.push(format!(
            "          - {title}: 10-validation-lab/experiments/{}.md",
            id(e)
        ));
    }
    lines.push(NAV_END.into());
    lines.join("\n")
}
pub fn replace_navigation(text: &str, navigation: &str) -> Result<String, String> {
    if text.matches(NAV_START).count() != 1 || text.matches(NAV_END).count() != 1 {
        return Err(
            "mkdocs.yml must contain exactly one pair of generated Lab navigation markers".into(),
        );
    }
    let start = text.find(NAV_START).unwrap();
    let end = text.find(NAV_END).unwrap();
    if end < start {
        return Err("Lab navigation markers are out of order".into());
    }
    Ok(format!(
        "{}{navigation}{}",
        &text[..start],
        &text[end + NAV_END.len()..]
    ))
}
