fn coverage(r: &Records) -> String {
    let mut p = Page::default();
    let vals = rows(r, "VAL-");
    p.lines(&[
        "## Authority and coverage boundary",
        "",
        COVERAGE_1,
        "",
        COVERAGE_2,
        "",
        "## Validation coverage",
        "",
    ]);
    p.table(
        &[
            "Validation",
            "Question",
            "Experiments",
            "Applicable tests",
            "Lifecycle",
            "Disposition",
        ],
        vals.iter()
            .map(|v| {
                vec![
                    format!("[{} r{}](#{})", id(v), s(&v["revision"]), low(v)),
                    c(&v["title"]),
                    a(&v["coverage"]["experiments"])
                        .iter()
                        .map(|e| {
                            format!(
                                "{} r{} ({})",
                                exp(id(e), ""),
                                s(&e["revision"]),
                                if e["mandatory"] == true {
                                    "mandatory"
                                } else {
                                    "supporting"
                                }
                            )
                        })
                        .collect::<Vec<_>>()
                        .join(", "),
                    format!(
                        "[{}](test-register.md#validation-test-map)",
                        a(&v["coverage"]["tests"]).len()
                    ),
                    c(&v["lifecycle"]["state"]),
                    cell(disposition(v, r)),
                ]
            })
            .collect(),
        "No validations registered.",
    );
    for v in vals {
        p.para(format!(
            "## {} — {} {{ #{} }}",
            id(v),
            s(&v["title"]),
            low(v)
        ));
        p.para(format!(
            "Revision {} · lifecycle {} · disposition {}",
            s(&v["revision"]),
            s(&v["lifecycle"]["state"]),
            disposition(v, r)
        ));
        p.para(format!("**Engineering objective:** {}", s(&v["objective"])));
        p.para(format!(
            "**Historical assessment:** {} · {}",
            s(&v["origin"]["source_status"]),
            s(&v["origin"]["source_refs"])
        ));
        p.para(s(&v["origin"]["finding"]));
        p.list(
            "**Required evidence**",
            a(&v["required_evidence"]).iter().map(s),
        );
        p.para(format!(
            "**Applicable tests:** {}.",
            a(&v["coverage"]["tests"])
                .iter()
                .map(|t| test(&r[&id(t)], ""))
                .collect::<Vec<_>>()
                .join(", ")
        ));
        p.para(format!(
            "**Current decision:** {}",
            v["current_decision_id"]
                .as_str()
                .map(|i| dec(i, ""))
                .unwrap_or_else(|| "None recorded; pending.".into())
        ));
    }
    p.finish("Validation coverage")
}
