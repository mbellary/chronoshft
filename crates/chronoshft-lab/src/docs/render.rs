fn s(v: &Value) -> String {
    match v {
        Value::String(s) => s.clone(),
        Value::Null => "None".into(),
        Value::Bool(b) => if *b { "True" } else { "False" }.into(),
        _ => v.to_string(),
    }
}
fn a(v: &Value) -> &[Value] {
    v.as_array().map(Vec::as_slice).unwrap_or(&[])
}
fn id(v: &Value) -> String {
    s(&v["id"])
}
fn low(v: &Value) -> String {
    id(v).to_lowercase()
}
fn cell(v: impl AsRef<str>) -> String {
    v.as_ref()
        .replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('|', "\\|")
        .replace('\n', "<br>")
}
fn c(v: &Value) -> String {
    cell(s(v))
}
fn join(v: &Value, separator: &str) -> String {
    a(v).iter().map(s).collect::<Vec<_>>().join(separator)
}
fn otherwise(s: String, fallback: &str) -> String {
    if s.is_empty() {
        fallback.into()
    } else {
        s
    }
}
fn rows<'a>(records: &'a Records, prefix: &str) -> Vec<&'a Value> {
    let mut result: Vec<_> = records
        .values()
        .filter(|r| id(r).starts_with(prefix))
        .collect();
    if ["VAL-", "EXP-", "TST-", "VDEC-"].contains(&prefix) {
        result.sort_by_cached_key(|r| {
            id(r)
                .split_once('-')
                .unwrap()
                .1
                .parse::<num_bigint::BigUint>()
                .unwrap_or_default()
        });
    }
    result
}
fn exp(identity: impl AsRef<str>, parent: &str) -> String {
    let i = identity.as_ref();
    format!("[{i}]({parent}experiments/{i}.md)")
}
fn test(t: &Value, parent: &str) -> String {
    format!(
        "[{}]({parent}experiments/{}.md#{})",
        id(t),
        s(&t["experiment"]["id"]),
        low(t)
    )
}
fn link(identity: impl AsRef<str>, kind: &str, parent: &str) -> String {
    let i = identity.as_ref();
    format!("[{i}]({parent}{kind}.md#{})", i.to_lowercase())
}
fn ev(i: impl AsRef<str>, p: &str) -> String {
    link(i, "evidence-register", p)
}
fn run(i: impl AsRef<str>, p: &str) -> String {
    link(i, "execution-register", p)
}
fn dec(i: impl AsRef<str>, p: &str) -> String {
    link(i, "validation-results", p)
}
fn val_ref(v: &Value, parent: &str) -> String {
    format!(
        "[{} r{}]({parent}validation-coverage.md#{})",
        id(v),
        s(&v["revision"]),
        low(v)
    )
}
fn disposition(v: &Value, records: &Records) -> String {
    v["current_decision_id"]
        .as_str()
        .map(|i| s(&records[i]["disposition"]))
        .unwrap_or_else(|| "pending".into())
}
fn summary(rows: &[&Value], key: impl Fn(&Value) -> String) -> String {
    let mut counts = BTreeMap::new();
    for r in rows {
        *counts.entry(key(r)).or_insert(0) += 1;
    }
    otherwise(
        counts
            .iter()
            .map(|(k, v)| format!("{v} {k}"))
            .collect::<Vec<_>>()
            .join(", "),
        "No records",
    )
}
#[derive(Default)]
struct Page(Vec<String>);
impl Page {
    fn lines(&mut self, lines: &[&str]) {
        self.0.extend(lines.iter().map(|s| s.to_string()));
    }
    fn para(&mut self, text: impl Into<String>) {
        self.0.push(text.into());
        self.0.push(String::new());
    }
    fn bullets(&mut self, values: impl IntoIterator<Item = String>) {
        let v: Vec<_> = values.into_iter().collect();
        if v.is_empty() {
            self.0.push("None recorded.".into());
        } else {
            self.0.extend(v.into_iter().map(|v| format!("- {v}")));
        }
    }
    fn list(&mut self, heading: &str, values: impl IntoIterator<Item = String>) {
        self.para(heading);
        self.bullets(values);
        self.0.push(String::new());
    }
    fn table(&mut self, headers: &[&str], rows: Vec<Vec<String>>, empty: &str) {
        if rows.is_empty() {
            self.para(empty);
            return;
        }
        self.0.push(format!("| {} |", headers.join(" | ")));
        self.0
            .push(format!("| {} |", vec!["---"; headers.len()].join(" | ")));
        self.0
            .extend(rows.iter().map(|r| format!("| {} |", r.join(" | "))));
        self.0.push(String::new());
    }
    fn finish(self, title: &str) -> String {
        format!(
            "# {title}\n\n{HEADER}\n\n{}\n",
            self.0.join("\n").trim_end()
        )
    }
}
