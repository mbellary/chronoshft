#[test]
fn legacy_generation_targets_are_checked_without_repair() {
    let d = fixture();
    for relative in [
        "docs/00-governance/validation-coverage.md",
        "docs/00-governance/validation-tests.md",
    ] {
        let path = d.path().join(relative);
        let original = fs::read(&path).unwrap();
        let mut stale = original.clone();
        stale.extend_from_slice(b"\nInvented manual status\n");
        fs::write(&path, &stale).unwrap();
        let errors = docs::generate(d.path(), true).unwrap_err();
        assert!(errors
            .iter()
            .any(|e| e.contains(relative) && e.contains("missing or stale")));
        assert_eq!(fs::read(&path).unwrap(), stale);
        fs::write(path, original).unwrap();
    }
    let page = d
        .path()
        .join("docs/10-validation-lab/experiments/EXP-001.md");
    fs::remove_file(&page).unwrap();
    let before = fs::read(d.path().join("mkdocs.yml")).unwrap();
    assert!(docs::generate(d.path(), true)
        .unwrap_err()
        .iter()
        .any(|e| e.contains("EXP-001.md is missing or stale")));
    assert!(!page.exists());
    assert_eq!(fs::read(d.path().join("mkdocs.yml")).unwrap(), before);
}
