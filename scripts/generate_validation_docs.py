def records_with(records, prefix):
    rows = [record for record in records.values() if record['id'].startswith(prefix)]
    if prefix in {'VAL-', 'EXP-', 'TST-', 'VDEC-'}:
        return sorted(rows, key=lambda record: int(record['id'].split('-')[1]))
    return sorted(rows, key=lambda record: record['id'])


def cell(value):
    return escape(str(value), quote=False).replace('|', '\\|').replace('\n', '<br>')


def page(title, lines):
    return '\n'.join([f'# {title}', '', HEADER, '', *lines]).rstrip() + '\n'


def bullets(values):
    return [f'- {value}' for value in values] or ['None recorded.']


def table(headers, rows, empty):
    if not rows:
        return [empty, '']
    return ['| ' + ' | '.join(headers) + ' |', '| ' + ' | '.join('---' for _ in headers) + ' |',
            *['| ' + ' | '.join(row) + ' |' for row in rows], '']


def exp_link(identity, parent=''):
    return f'[{identity}]({parent}experiments/{identity}.md)'


def test_link(test, parent=''):
    return f"[{test['id']}]({parent}experiments/{test['experiment']['id']}.md#{test['id'].lower()})"


def evidence_link(identity, parent=''):
    return f'[{identity}]({parent}evidence-register.md#{identity.lower()})'


def run_link(identity, parent=''):
    return f'[{identity}]({parent}execution-register.md#{identity.lower()})'


def decision_link(identity, parent=''):
    return f'[{identity}]({parent}validation-results.md#{identity.lower()})'


def disposition(val, records):
    identity = val['current_decision_id']
    return records[identity]['disposition'] if identity else 'pending'


def state_summary(rows, key):
    counts = Counter(key(row) for row in rows)
    return ', '.join(f'{count} {state}' for state, count in sorted(counts.items())) or 'No records'


