def render_navigation(records):
    pages = [('Overview', 'index'), ('Methodology', 'methodology'), ('Validation coverage', 'validation-coverage'),
             ('Experiment register', 'experiment-register'), ('Test register', 'test-register'),
             ('Execution register', 'execution-register'), ('Evidence register', 'evidence-register'),
             ('Validation results', 'validation-results'), ('Environment profiles', 'environment-profiles'), ('Automation and CI', 'automation-and-ci'), ('Execution and evidence', 'execution-and-evidence')]
    lines = [NAV_START, '  - Technical Validation Lab:']
    lines += [f'      - {label}: 10-validation-lab/{filename}.md' for label, filename in pages]
    lines += ['      - Experiments:']
    lines += [f"          - {json.dumps(exp['id'] + ' — ' + exp['title'], ensure_ascii=False)}: 10-validation-lab/experiments/{exp['id']}.md" for exp in records_with(records, 'EXP-')]
    return '\n'.join([*lines, NAV_END])


def replace_navigation(text, navigation):
    if text.count(NAV_START) != 1 or text.count(NAV_END) != 1:
        raise ValueError('mkdocs.yml must contain exactly one pair of generated Lab navigation markers')
    start = text.index(NAV_START)
    end = text.index(NAV_END) + len(NAV_END)
    if text.index(NAV_END) < start:
        raise ValueError('Lab navigation markers are out of order')
    return text[:start] + navigation + text[end:]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=ROOT)
    parser.add_argument('--check', action='store_true', help='fail if generated pages or Lab navigation are missing or stale')
    args = parser.parse_args()
    root = args.root.resolve()
    errors, records = validate(root, require_tests=True)
    if errors:
        print('\n'.join(errors), file=sys.stderr)
        return 1
    outputs = generated_documents(records)
    expected_experiments = {path for path in outputs if path.parent == LAB / 'experiments'}
    extras = [path.relative_to(root) for path in (root / LAB / 'experiments').glob('*.md') if path.relative_to(root) not in expected_experiments]
    if extras:
        print('Unregistered experiment pages: ' + ', '.join(map(str, extras)), file=sys.stderr)
        return 1
    try:
        original_nav = (root / 'mkdocs.yml').read_text(encoding='utf-8')
        outputs[Path('mkdocs.yml')] = replace_navigation(original_nav, render_navigation(records))
    except (OSError, ValueError) as exc:
        print(str(exc), file=sys.stderr)
        return 1
    for authored in ('methodology.md', 'automation-and-ci.md', 'execution-and-evidence.md'):
        if not (root / LAB / authored).is_file():
            print(f'The authored Lab page {authored} is missing.', file=sys.stderr)
            return 1
    stale = False
    for relative, content in outputs.items():
        path = root / relative
        if args.check:
            if not path.is_file() or path.read_text(encoding='utf-8') != content:
                print(f'{relative} is missing or stale; regenerate validation documentation.', file=sys.stderr)
                stale = True
        elif not path.is_file() or path.read_text(encoding='utf-8') != content:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding='utf-8')
    if stale:
        return 1
    print(f"{'Checked' if args.check else 'Generated'} {len(outputs) - 1} validation pages and Lab navigation.")
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
